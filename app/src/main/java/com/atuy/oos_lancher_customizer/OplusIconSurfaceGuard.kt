package com.atuy.oos_lancher_customizer

import android.content.ComponentName
import android.content.Context
import android.graphics.drawable.BitmapDrawable
import android.graphics.drawable.Drawable
import android.util.Log
import android.util.LruCache
import android.view.View
import io.github.libxposed.api.XposedInterface
import io.github.libxposed.api.XposedModule
import io.github.libxposed.api.XposedModuleInterface.PackageLoadedParam
import java.lang.reflect.Field
import java.lang.reflect.Method
import java.lang.reflect.Proxy
import java.lang.ref.WeakReference
import java.util.Collections
import java.util.WeakHashMap

/**
 * Keeps the OxygenOS swipe-to-home IconSurface animation visually identical to the
 * BitmapDrawable generated by ThemedIcons.
 *
 * OOS has a second app-close pipeline under anim/iconsurfacemanager. It can reconstruct a
 * FastBitmapDrawable from package metadata even when the workspace/folder preview has already
 * been replaced by this module. For folder targets this caused the original icon to flash.
 *
 * The important detail is hook ordering:
 * - BubbleTextView#setIcon is captured at PRIORITY_LOWEST. ThemedIcons runs first at the
 *   default priority and passes its themed BitmapDrawable to this hook.
 * - PreviewItemManager#setDrawable is captured at PRIORITY_HIGHEST and inspected after
 *   chain.proceed() returns. ThemedIcons performs its folder-preview replacement while the
 *   call unwinds, so the field now contains the exact themed BitmapDrawable.
 *
 * Only BitmapDrawable results are cached here because ThemedIcons always produces one. This
 * prevents an unthemed Launcher FastBitmapDrawable from poisoning the IconSurface cache.
 */
class OplusIconSurfaceGuard : XposedModule() {

    companion object {
        private const val TAG = "OOS16_ThemedSurfaceGuard"
        private const val TARGET_PACKAGE = "com.android.launcher"
        private const val BTV_CLASS = "com.android.launcher3.BubbleTextView"
        private const val PREVIEW_MANAGER_CLASS =
            "com.android.launcher3.folder.PreviewItemManager"
        private const val ICON_VIEW_MANAGER_CLASS =
            "com.android.launcher3.anim.iconsurfacemanager.IconViewManager"
        private const val ICON_SURFACE_RECORD_CLASS =
            "com.android.launcher3.anim.iconsurfacemanager.IconSurfaceRecord"
        private const val NEW_ICON_DRAWABLE_LOADER =
            "com.android.launcher3.anim.iconsurfacemanager.loader.IconDrawableLoader"
    }

    @Volatile
    private var hooksInstalled = false

    private val themedStates = object : LruCache<String, Drawable.ConstantState>(256) {}

    // A folder-close animation may target BigFolderItemIcon while ItemInfo identifies the app.
    private data class TargetOverride(val key: String, val state: Drawable.ConstantState)

    private val targetOverrides =
        Collections.synchronizedMap(WeakHashMap<View, TargetOverride>())

    private data class NewLoaderTarget(
        val key: String,
        val state: Drawable.ConstantState,
        val view: WeakReference<View>,
        val item: Any
    )
    private val loaderOverrides =
        Collections.synchronizedMap(WeakHashMap<Any, NewLoaderTarget>())

    override fun onPackageLoaded(param: PackageLoadedParam) {
        if (param.packageName != TARGET_PACKAGE || hooksInstalled) return

        runCatching {
            installHooks(param.defaultClassLoader)
            hooksInstalled = true
        }.onFailure {
            moduleLog("critical: ${it.message}", it)
        }
    }

    private fun installHooks(classLoader: ClassLoader) {
        val managerClass = runCatching {
            Class.forName(ICON_VIEW_MANAGER_CLASS, false, classLoader)
        }.getOrNull()
        val recordClass = runCatching {
            Class.forName(ICON_SURFACE_RECORD_CLASS, false, classLoader)
        }.getOrNull()
        val newLoaderClass = runCatching {
            Class.forName(NEW_ICON_DRAWABLE_LOADER, false, classLoader)
        }.getOrNull()
        if ((managerClass == null || recordClass == null) && newLoaderClass == null) {
            moduleLog("no supported IconSurface pipeline; skipping")
            return
        }

        val bubbleClass = Class.forName(BTV_CLASS, false, classLoader)
        hookAllNamedMethods(
            bubbleClass,
            "setIcon",
            "surface-capture-bubble",
            XposedInterface.PRIORITY_LOWEST
        ) { chain ->
            val args = chain.args.toTypedArray()
            captureThemedBubbleArgument(chain.thisObject, args)
            chain.proceed(args)
        }
        moduleLog("hooked BubbleTextView#setIcon exact themed capture")

        runCatching {
            val previewClass = Class.forName(PREVIEW_MANAGER_CLASS, false, classLoader)
            hookAllNamedMethods(
                previewClass,
                "setDrawable",
                "surface-capture-preview",
                XposedInterface.PRIORITY_HIGHEST
            ) { chain ->
                val args = chain.args.toTypedArray()
                val result = chain.proceed(args)
                captureThemedPreviewResult(chain.thisObject, args)
                result
            }
            moduleLog("hooked PreviewItemManager#setDrawable exact themed capture")
        }.onFailure {
            moduleLog("PreviewItemManager capture skipped: ${it.message}")
        }

        if (managerClass == null || recordClass == null) {
            installNewSurfaceHooks(newLoaderClass!!)
            return
        }

        hookAllNamedMethods(managerClass, "fetchIcon", "surface-fetchIcon") { chain ->
            val args = chain.args.toTypedArray()
            armTargetOverride(args)
            chain.proceed(args)
        }

        hookAllNamedMethods(
            managerClass,
            "getIconResultForAsync",
            "surface-async-result"
        ) { chain ->
            val args = chain.args.toTypedArray()
            armTargetOverride(args)
            replaceDrawableArgumentFromItemInfo(args)
            chain.proceed(args)
        }

        moduleLog("hooked IconViewManager IconSurface sources")

        hookAllNamedMethods(recordClass, "onIconLoaded", "surface-final-sink") { chain ->
            val args = chain.args.toTypedArray()
            beforeIconSurfaceLoaded(args)
            chain.proceed(args)
        }
        moduleLog("hooked IconSurfaceRecord#onIconLoaded")
    }

    /**
     * Oplus Launcher 17.3.12 moved IconSurface rendering to IconDrawableLoader.
     * Instead of returning a BitmapDrawable from getFancyIconBitmapDrawable (whose
     * declared return type is FastBitmapDrawable), intercept the interface callback
     * carrying the final Drawable. That avoids type mismatches and preserves geometry.
     */
    private fun installNewSurfaceHooks(loaderClass: Class<*>) {
        hookAllNamedMethods(loaderClass, "getIconResultForAsync", "surface-v17-async") { chain ->
            val args = chain.args.toTypedArray()
            armNewLoaderTarget(chain.thisObject, args)
            chain.proceed(args)
        }

        hookAllNamedMethods(loaderClass, "getIcon", "surface-v17-callback") { chain ->
            val args = chain.args.toTypedArray()
            wrapNewLoaderCallback(chain.thisObject, args)
            chain.proceed(args)
        }

        hookAllNamedMethods(loaderClass, "release", "surface-v17-release") { chain ->
            chain.thisObject?.let(loaderOverrides::remove)
            chain.proceed()
        }
        moduleLog("hooked ColorOS 17 IconDrawableLoader async and final callback")
    }

    private fun armNewLoaderTarget(owner: Any?, args: Array<Any?>) {
        if (owner == null) return
        loaderOverrides.remove(owner)
        val view = args.getOrNull(1) as? View ?: return
        val item = args.getOrNull(2) ?: return
        if (!ThemedIconPolicy.shouldThemeSurfaceTarget(view, item)) return

        val key = ThemedIconPolicy.itemKey(item)
        var state = themedStates.get(key)
        if (state == null) {
            // The display icon may have been captured under the original view ItemInfo
            // rather than the cloned ItemInfo passed to IconDrawableLoader.
            val viewItem = ThemedIconPolicy.itemForView(view)
            if (viewItem != null && ThemedIconPolicy.shouldThemeAnimation(view, viewItem)) {
                state = themedStates.get(ThemedIconPolicy.itemKey(viewItem))
            }
        }
        val validState = state ?: return
        loaderOverrides[owner] = NewLoaderTarget(key, validState, WeakReference(view), item)
        moduleLog("new surface target armed item=$key view=${view.javaClass.simpleName}")
    }

    private fun wrapNewLoaderCallback(owner: Any?, args: Array<Any?>) {
        if (owner == null) return
        val originalCallback = args.getOrNull(0) ?: return
        val callbackInterface = runCatching {
            Class.forName(
                "com.android.launcher3.anim.iconsurfacemanager.loader.IconViewCallback",
                false, owner.javaClass.classLoader
            )
        }.getOrNull() ?: return
        if (!callbackInterface.isInstance(originalCallback)) return
        val wrapper = Proxy.newProxyInstance(
            callbackInterface.classLoader,
            arrayOf(callbackInterface)
        ) { _, method, supplied ->
            val values = supplied?.copyOf() ?: emptyArray()
            if (method.name == "onDrawableLoaded" && values.firstOrNull() is Drawable) {
                val target = loaderOverrides[owner]
                val view = target?.view?.get()
                if (target != null && view != null &&
                    ThemedIconPolicy.shouldThemeSurfaceTarget(view, target.item)) {
                    val original = values[0] as Drawable
                    val replacement = newDrawable(target.state, view.context)
                    replacement.bounds = original.bounds
                    values[0] = replacement
                    moduleLog("new surface callback themed item=${target.key}")
                }
            }
            method.invoke(originalCallback, *values)
        }
        args[0] = wrapper
    }

    private fun hookAllNamedMethods(
        clazz: Class<*>,
        methodName: String,
        hookIdPrefix: String,
        priority: Int = XposedInterface.PRIORITY_DEFAULT,
        interceptor: (XposedInterface.Chain) -> Any?
    ) {
        val methods = clazz.declaredMethods.filter { it.name == methodName }
        check(methods.isNotEmpty()) { "${clazz.name}#$methodName not found" }

        methods.forEach { method ->
            method.isAccessible = true
            val signature = method.parameterTypes.joinToString(",") { it.name }
            hook(method)
                .setPriority(priority)
                .setId("$hookIdPrefix-${clazz.simpleName}($signature)")
                .intercept { chain -> interceptor(chain) }
        }
    }

    /**
     * At PRIORITY_LOWEST, ThemedIcons has already rewritten arg[0] before reaching us.
     */
    private fun captureThemedBubbleArgument(owner: Any?, args: Array<Any?>) {
        val view = owner as? View ?: return
        val itemInfo = runCatching { view.tag }.getOrNull() ?: return
        val pkg = resolvePackageName(itemInfo) ?: return
        if (!shouldPatch(pkg) || !ThemedIconPolicy.shouldThemeView(view, itemInfo)) return

        val themed = args.firstOrNull() as? BitmapDrawable ?: return
        rememberExactThemed(itemInfo, themed, "bubble")
    }

    /**
     * At PRIORITY_HIGHEST we wrap ThemedIcons. Its after-original mutation is therefore
     * complete when chain.proceed() returns here.
     */
    private fun captureThemedPreviewResult(owner: Any?, args: Array<Any?>) {
        val previewParams = args.firstOrNull() ?: return
        val itemInfo = args.getOrNull(1) ?: return
        val pkg = resolvePackageName(itemInfo) ?: return
        if (!shouldPatch(pkg) || !ThemedIconPolicy.shouldThemeFolderPreview(owner, itemInfo)) return

        val themed = readField(previewParams, "drawable") as? BitmapDrawable ?: return
        rememberExactThemed(itemInfo, themed, "preview")
    }

    private fun rememberExactThemed(itemInfo: Any, drawable: BitmapDrawable, source: String) {
        if (!ThemedIconPolicy.isThemedDrawable(drawable)) return
        val state = drawable.constantState ?: return
        themedStates.put(ThemedIconPolicy.itemKey(itemInfo), state)
        moduleLog(
            "exact themed cached item=${ThemedIconPolicy.itemKey(itemInfo)} source=$source " +
                "${drawable.javaClass.simpleName} ${drawable.intrinsicWidth}x${drawable.intrinsicHeight}"
        )
    }

    /**
     * Known IconViewManager methods begin with (Launcher, View, ItemInfo, ...).
     */
    private fun armTargetOverride(args: Array<Any?>) {
        val view = args.getOrNull(1) as? View ?: return
        targetOverrides.remove(view)
        val itemInfo = args.getOrNull(2) ?: return
        if (!ThemedIconPolicy.shouldThemeAnimation(view, itemInfo)) return
        val key = ThemedIconPolicy.itemKey(itemInfo)
        val state = themedStates.get(key) ?: return
        targetOverrides[view] = TargetOverride(key, state)
    }

    private fun replaceDrawableArgumentFromItemInfo(args: Array<Any?>) {
        val context = (args.getOrNull(0) as? Context)
            ?: (args.getOrNull(1) as? View)?.context
            ?: return
        val itemInfo = args.getOrNull(2) ?: return
        val pkg = resolvePackageName(itemInfo) ?: return
        if (!shouldPatch(pkg) ||
            !ThemedIconPolicy.shouldThemeAnimation(args.getOrNull(1) as? View, itemInfo)) return

        val state = themedStates.get(ThemedIconPolicy.itemKey(itemInfo)) ?: return
        val drawableIndex = args.indexOfFirst { it is Drawable }
        if (drawableIndex < 0) return

        val original = args[drawableIndex] as? Drawable
        val replacement = newDrawable(state, context)
        replacement.bounds = original?.bounds ?: replacement.bounds
        args[drawableIndex] = replacement
        moduleLog(
            "async source forced pkg=$pkg ${original?.javaClass?.simpleName} -> " +
                replacement.javaClass.simpleName
        )
    }

    private fun replacementForView(view: View?): Drawable? {
        if (view == null) return null
        val itemInfo = ThemedIconPolicy.itemForView(view) ?: return null
        if (!ThemedIconPolicy.shouldThemeAnimation(view, itemInfo)) {
            targetOverrides.remove(view)
            return null
        }
        val key = ThemedIconPolicy.itemKey(itemInfo)
        val override = targetOverrides[view]
        if (override != null && override.key == key) {
            return newDrawable(override.state, view.context)
        }
        targetOverrides.remove(view)
        val state = themedStates.get(key) ?: return null
        return newDrawable(state, view.context)
    }

    private fun beforeIconSurfaceLoaded(args: Array<Any?>) {
        // Current OOS signature:
        // (View, SurfaceSession, Launcher, boolean, LoadSurfaceSizeParams, boolean,
        //  Drawable, boolean, boolean, RectF, IconSurfaceCallback)
        val view = args.firstOrNull() as? View ?: return
        val drawableIndex = args.indexOfFirst { it is Drawable }
        if (drawableIndex < 0) return

        val replacement = replacementForView(view) ?: return
        val original = args[drawableIndex] as? Drawable
        replacement.bounds = original?.bounds ?: replacement.bounds
        args[drawableIndex] = replacement

        moduleLog(
            "surface sink forced view=${view.javaClass.simpleName} " +
                "${original?.javaClass?.simpleName} -> ${replacement.javaClass.simpleName}"
        )
    }

    private fun newDrawable(state: Drawable.ConstantState, context: Context): Drawable {
        return state.newDrawable(context.resources).mutate()
    }

    private fun shouldPatch(pkg: String): Boolean {
        return pkg.isNotBlank() && pkg != TARGET_PACKAGE
    }

    private fun resolvePackageName(itemInfo: Any): String? {
        (readField(itemInfo, "componentName") as? ComponentName)
            ?.packageName
            ?.let { return it }

        (invokeNoArg(itemInfo, "getTargetComponent") as? ComponentName)
            ?.packageName
            ?.let { return it }

        (invokeNoArg(itemInfo, "getMTargetComponent") as? ComponentName)
            ?.packageName
            ?.let { return it }

        (readField(itemInfo, "packageName") as? String)
            ?.takeIf { it.contains('.') }
            ?.let { return it }

        (invokeNoArg(itemInfo, "getTargetPackage") as? String)
            ?.takeIf { it.contains('.') }
            ?.let { return it }

        return null
    }

    private fun findField(owner: Any, name: String): Field? {
        var cls: Class<*>? = owner.javaClass
        while (cls != null) {
            val current = cls
            val field = runCatching {
                current.getDeclaredField(name).apply { isAccessible = true }
            }.getOrNull()
            if (field != null) return field
            cls = current.superclass
        }
        return null
    }

    private fun readField(owner: Any?, name: String): Any? {
        if (owner == null) return null
        return runCatching { findField(owner, name)?.get(owner) }.getOrNull()
    }

    private fun findNoArgMethod(owner: Any, name: String): Method? {
        var cls: Class<*>? = owner.javaClass
        while (cls != null) {
            val current = cls
            val method = current.declaredMethods.firstOrNull {
                it.name == name && it.parameterCount == 0
            }
            if (method != null) {
                method.isAccessible = true
                return method
            }
            cls = cls.superclass
        }
        return null
    }

    private fun invokeNoArg(owner: Any, name: String): Any? {
        return runCatching { findNoArgMethod(owner, name)?.invoke(owner) }.getOrNull()
    }

    private fun moduleLog(msg: String, throwable: Throwable? = null) {
        if (throwable == null) {
            log(Log.INFO, TAG, msg)
        } else {
            log(Log.ERROR, TAG, msg, throwable)
        }
    }
}
